#!/usr/bin/env python3
"""Install pinned Isaac ROS 4.4/VPI runtime into .cache/vslam, without sudo.

Uses the host's ROS 2 Jazzy, NVIDIA driver and CUDA 13 runtime. This is a
relocated runtime overlay, not a replacement for a complete Isaac ROS SDK.
"""
import concurrent.futures
import hashlib
import json
import os
from pathlib import Path
import shlex
import shutil
import subprocess

ROOT = Path(__file__).resolve().parents[2]
BASE = ROOT / '.cache/vslam'
MANIFEST = Path(__file__).with_name('vio_runtime_packages.json')


def digest(path):
    with path.open('rb') as stream:
        return hashlib.file_digest(stream, 'sha256').hexdigest()


def main():
    for command in ('curl', 'dpkg-deb', 'nvidia-smi'):
        if not shutil.which(command):
            raise SystemExit(f'Missing host prerequisite: {command}')
    if not Path('/opt/ros/jazzy').is_dir():
        raise SystemExit('Install ROS 2 Jazzy first')
    packages = json.loads(MANIFEST.read_text())
    debs, sysroot = BASE/'debs', BASE/'root'
    debs.mkdir(parents=True, exist_ok=True)
    sysroot.mkdir(parents=True, exist_ok=True)

    def download(package):
        target = debs/package['url'].rsplit('/', 1)[-1]
        if not target.exists() or digest(target) != package['sha256']:
            temporary = target.with_suffix('.download')
            subprocess.run(['curl', '--fail', '--location', '--retry', '3',
                            '--silent', '--show-error', package['url'], '-o', str(temporary)], check=True)
            if digest(temporary) != package['sha256']:
                raise RuntimeError('Checksum mismatch: ' + package['name'])
            temporary.replace(target)
        print('Verified ' + package['name'] + ' ' + package['version'], flush=True)
        return target

    with concurrent.futures.ThreadPoolExecutor(max_workers=6) as pool:
        archives = list(pool.map(download, packages))
    installed = BASE/'installed_packages.json'
    same_install = (installed.exists() and json.loads(installed.read_text()) == packages
                    and (sysroot/'opt/ros/jazzy/lib/libvisual_slam_node.so').exists()
                    and (sysroot/'opt/nvidia/vpi4/lib/x86_64-linux-gnu/libnvvpi.so.4').exists())
    if not same_install:
        for archive in archives:
            subprocess.run(['dpkg-deb', '-x', str(archive), str(sysroot)], check=True)
    prefix = sysroot/'opt/ros/jazzy'
    libraries = sorted({str(path.parent) for path in sysroot.rglob('*.so*') if path.is_file()})
    if Path('/usr/local/cuda/lib64').is_dir():
        libraries.append('/usr/local/cuda/lib64')
    environment = (
        '# Generated by scripts/setup/setup_vio_dependencies.py\n'
        f'export AMENT_PREFIX_PATH={shlex.quote(str(prefix))}:"${{AMENT_PREFIX_PATH:-}}"\n'
        f'export LD_LIBRARY_PATH={shlex.quote(":".join(libraries))}:"${{LD_LIBRARY_PATH:-}}"\n'
        f'export PYTHONPATH={shlex.quote(str(prefix/"lib/python3.12/site-packages"))}:"${{PYTHONPATH:-}}"\n'
    )
    (BASE/'env.bash').write_text(environment)
    (BASE/'installed_packages.json').write_text(json.dumps(packages, indent=2)+'\n')
    check_env = dict(os.environ)
    check_env['LD_LIBRARY_PATH'] = ':'.join(libraries)+':'+check_env.get('LD_LIBRARY_PATH','')
    linkage = subprocess.check_output(['ldd', str(prefix/'lib/libvisual_slam_node.so')],
                                      env=check_env, text=True)
    (BASE/'linkage.txt').write_text(linkage)
    missing = [line.strip() for line in linkage.splitlines() if 'not found' in line]
    if missing:
        raise SystemExit('Missing host ROS/CUDA libraries (source Jazzy first):\n'+'\n'.join(missing))
    print(f'Runtime ready: source {BASE}/env.bash (after ROS/workspace setup)')


if __name__ == '__main__':
    main()
